import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createStudioAdmin } = require('../lib/studio-admin.cjs');
const root = process.cwd(), tempRoot = path.join(root, 'work', 'tmp');
await fs.mkdir(tempRoot, { recursive: true });
const fixture = await fs.mkdtemp(path.join(tempRoot, 'admin-'));
const site = path.join(fixture, 'site');
const seed = async (name, text) => { const target = path.join(fixture, name); await fs.mkdir(path.dirname(target), { recursive: true }); await fs.writeFile(target, text); };
const source = '---\ntitle: 原来的手记\ndate: 2026-10-19 12:00:00\n---\n\n原来的内容。\n';
let server;
try {
  await seed('_config.yml', await fs.readFile(path.join(root, '_config.yml'), 'utf8'));
  await seed('site/_config.yml', await fs.readFile(path.join(root, 'studio-content/site.yml'), 'utf8'));
  await seed('site/source/_posts/example.md', source);
  await seed('studio-content/source/_posts/example.md', source);
  await seed('site/source/reviews/data.json', '{"reviews":[]}');
  const middleware = createStudioAdmin({ projectRoot: fixture, siteDir: site });
  server = http.createServer((req, res) => middleware(req, res, () => { res.statusCode = 404; res.end(); }));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}/__studio_api/`;
  const discovery = await (await fetch(base + 'status')).json(); assert.equal(discovery.mode, 'local');
  const call = async (route, body, method = body ? 'PUT' : 'GET', extra = {}) => {
    const response = await fetch(base + route, { method, headers: { 'X-Studio-Session': discovery.nonce, ...(body ? { 'Content-Type': 'application/json' } : {}), ...extra }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { code: response.status, data: await response.json() };
  };
  assert.equal((await fetch(base + 'state')).status, 403);
  assert.equal((await call('state', null, 'GET', { Origin: 'https://other.example' })).code, 403);
  const state = (await call('state')).data; assert.equal(state.files.length, 1);
  assert.equal((await call('file', { path: 'studio-content/source/../_config.yml', content: 'bad' })).code, 400);
  assert.equal((await call('file', { ...state.files[0], sha: 'outdated' })).code, 409);
  const next = source + '\n后台保存测试。\n';
  const saved = await call('file', { ...state.files[0], content: next }); assert.equal(saved.code, 200);
  assert.equal(await fs.readFile(path.join(fixture, state.files[0].path), 'utf8'), next);
  assert.equal(await fs.readFile(path.join(site, 'source/_posts/example.md'), 'utf8'), next);
  assert.equal((await call('file', state.files[0])).code, 409, 'Stale editor cannot overwrite a newer save');
  assert.equal((await call('settings', { ...state.settings, version: 'stale' })).code, 409);
  assert.equal((await call('settings', { ...state.settings, site: { ...state.settings.site, url: 'javascript:alert(1)' } })).code, 400);
  const updated = { ...state.settings, site: { ...state.settings.site, subtitle: '后台设置测试' } };
  assert.equal((await call('settings', updated)).code, 200);
  assert((await fs.readFile(path.join(fixture, 'studio-content/site.yml'), 'utf8')).includes('后台设置测试'));
  assert.equal((await call('reviews', { target: '不存在', rating: 5, content: '评价内容够五个字。' }, 'POST')).code, 400);
  const target = state.settings.studio.members[0].name;
  assert.equal((await call('reviews', { target, rating: 6, content: '评价内容够五个字。' }, 'POST')).code, 400);
  assert.equal((await call('reviews', { target, rating: 4, content: '配合很默契，下次还一起玩。' }, 'POST')).code, 201);
  let reviews = (await call('reviews')).data;
  assert.equal(reviews.pending.length, 1); assert.equal(reviews.approved.length, 0);
  assert.equal((await call('reviews', { target, rating: 4, content: '重复提交需要限流。' }, 'POST')).code, 429);
  const id = reviews.pending[0].id;
  let result = await call('review', { id, action: 'approve' }); assert.equal(result.code, 200); assert.equal(result.data.pending.length, 0); assert.equal(result.data.approved.length, 1);
  const canonical = JSON.parse(await fs.readFile(path.join(fixture, 'studio-content/source/reviews/data.json'), 'utf8'));
  assert.equal(canonical.reviews[0].rating, 4); assert(!('status' in canonical.reviews[0]));
  assert.equal((await call('review', { id, action: 'approve' })).code, 409);
  assert.equal((await call('review', { id, action: 'remove' })).code, 200);
  assert.equal((await call('reviews')).data.approved.length, 0);
  assert((await fs.readdir(path.join(fixture, 'work/admin-backups'))).length >= 4);
  const longContent = '中文评价与手记🌿'.repeat(12000);
  const uploadBody = Buffer.from(JSON.stringify({ path: 'studio-content/source/_posts/utf8.md', content: longContent, sha: null }));
  const splitAt = uploadBody.indexOf(Buffer.from('中文')) + 1;
  const utf8Status = await new Promise((resolve, reject) => {
    const upload = http.request(new URL(base + 'file'), { method: 'PUT', headers: { 'X-Studio-Session': discovery.nonce, 'Content-Type': 'application/json', 'Content-Length': uploadBody.length } }, response => { response.resume(); response.on('end', () => resolve(response.statusCode)); });
    upload.on('error', reject); upload.write(uploadBody.subarray(0, splitAt)); setTimeout(() => upload.end(uploadBody.subarray(splitAt)), 10);
  });
  assert.equal(utf8Status, 200);
  assert.equal(await fs.readFile(path.join(fixture, 'studio-content/source/_posts/utf8.md'), 'utf8'), longContent, 'UTF-8 survives a multibyte character split across request chunks');
  console.log('PASS local CMS: session/origin, editable paths, mirrored saves, conflicts, settings, review validation/rate limit/moderation and backups');
} finally {
  if (server) await new Promise(resolve => server.close(resolve));
  assert(path.resolve(fixture).startsWith(path.resolve(tempRoot) + path.sep));
  await fs.rm(fixture, { recursive: true, force: true });
}
